#!/usr/bin/env python3
"""Writes src/key_codes.cc: each platform's key code by physical key.

The framework reads a legacy key message's physical key from the platform's
code in it (macOS keyCode, Linux and Windows scanCode) through its own maps
in keyboard_maps.g.dart. This reverses those maps, so the runner can name
the code for the physical key a client sends.

    tool/key_codes.py <flutter SDK>
"""
import re
import sys
from pathlib import Path

PLATFORMS = [
    ("__APPLE__", "kMacOsToPhysicalKey"),
    ("_WIN32", "kWindowsToPhysicalKey"),
    (None, "kLinuxToPhysicalKey"),
]


def main():
    services = Path(sys.argv[1]) / "packages/flutter/lib/src/services"
    keys = (services / "keyboard_key.g.dart").read_text()
    usage = {
        name: int(value, 16)
        for name, value in re.findall(
            r"static const PhysicalKeyboardKey (\w+) = PhysicalKeyboardKey\((0x[0-9a-fA-F]+)\)",
            keys)
    }
    maps = (services / "keyboard_maps.g.dart").read_text()
    out = [
        "// Generated by tool/key_codes.py from the Flutter SDK's",
        "// keyboard_maps.g.dart; do not edit.",
        '#include "key_codes.h"',
        "",
        "#include <iterator>",
        "",
        "namespace raccoon {",
        "",
        "namespace {",
        "",
    ]
    for index, (macro, name) in enumerate(PLATFORMS):
        body = re.search(
            name + r" = <int, PhysicalKeyboardKey>\{(.*?)\n\};", maps, re.S).group(1)
        codes = {}
        for code, key in re.findall(r"(0x[0-9a-fA-F]+|[0-9]+): PhysicalKeyboardKey\.(\w+)", body):
            codes.setdefault(usage[key], int(code, 0))
        pairs = sorted(codes.items())
        out.append(("#if" if index == 0 else "#elif") + f" defined({macro})" if macro else "#else")
        out.append(f"// {name}, reversed.")
        out.append("constexpr uint32_t kUsages[] = {")
        out += wrap(f"0x{u:x}" for u, _ in pairs)
        out.append("};")
        out.append("constexpr uint16_t kCodes[] = {")
        out += wrap(f"0x{c:x}" for _, c in pairs)
        out.append("};")
    out += [
        "#endif",
        "",
        "}  // namespace",
        "",
        "uint64_t PlatformKeyCode(uint64_t physical) {",
        "  for (size_t i = 0; i < std::size(kUsages); ++i) {",
        "    if (kUsages[i] == physical) return kCodes[i];",
        "  }",
        "  return physical;",
        "}",
        "",
        "}  // namespace raccoon",
        "",
    ]
    target = Path(__file__).resolve().parent.parent / "src" / "key_codes.cc"
    target.write_text("\n".join(out))


def wrap(items):
    lines, line = [], "   "
    for item in items:
        if len(line) + len(item) + 2 > 100:
            lines.append(line)
            line = "   "
        line += " " + item + ","
    lines.append(line)
    return lines


if __name__ == "__main__":
    main()

import 'dart:io';

import 'package:path/path.dart' as p;

/// The entry point a run starts an app with to show it as a device (#194):
/// the device's safe area as the `MediaQuery` padding of each view, and its
/// platform as `defaultTargetPlatform`, neither of which the engine can
/// say. With `views`, the app in every view the runner gives it as well
/// (#182). Then it calls the app's own `main`.
///
/// It asks the client on [channel] at start and whenever the metrics
/// change; `DeviceChannel` answers. With no answer the app is shown as the
/// host. An app that reads `View.of(context).padding` rather than
/// `MediaQuery` sees no safe area, and `Platform.isIOS` stays false.
abstract final class RaccoonEntrypoint {
  /// Where [write] puts the entry point, relative to the project.
  static final path = p.join('.dart_tool', 'raccoon', 'main.dart');

  /// Where [write] puts the views entry point, relative to the project.
  static final viewsPath = p.join('.dart_tool', 'raccoon', 'views_main.dart');

  /// The channel the entry asks for its view's device on.
  static const channel = 'raccoon/device';

  /// Writes the entry point for the project at [projectDirectory], whose
  /// main library is [target] (relative to it), and returns its path. Null
  /// when [target] is not under `lib/` or the pubspec names no package:
  /// the entry imports it by its package URI, so its libraries are the ones
  /// the rest of the app imports, not copies by file.
  static String? write(
    String projectDirectory, {
    String target = 'lib/main.dart',
    bool views = false,
  }) {
    final package = packageOf(projectDirectory);
    final relative = p.posix.joinAll(p.split(p.normalize(target)));
    if (package == null || !relative.startsWith('lib/')) return null;
    final file = File(p.join(projectDirectory, views ? viewsPath : path))
      ..parent.createSync(recursive: true);
    final source = sourceFor(
      'package:$package/${relative.substring(4)}',
      views: views,
    );
    // Unchanged, it is left be: a rewrite would make the tool compile anew.
    if (!file.existsSync() || file.readAsStringSync() != source) {
      file.writeAsStringSync(source);
    }
    return file.path;
  }

  /// The package the pubspec in [projectDirectory] names, or null.
  static String? packageOf(String projectDirectory) {
    final pubspec = File(p.join(projectDirectory, 'pubspec.yaml'));
    if (!pubspec.existsSync()) return null;
    return RegExp(
      r'^name:\s*([A-Za-z0-9_]+)',
      multiLine: true,
    ).firstMatch(pubspec.readAsStringSync())?.group(1);
  }

  /// The entry point's source, importing the app's main from [mainImport].
  static String sourceFor(String mainImport, {bool views = false}) => '''
// Generated by Raccoon: the app shown as a device${views ? ', in every view it is given' : ''}.
// Rewritten as needed; edits here are lost.

import 'dart:math' as math;

import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';
import 'package:flutter/widgets.dart';

import '$mainImport' as app;

void main(List<String> args) {
  _RaccoonBinding();
  final Function entry = app.main;
  if (entry is dynamic Function(List<String>)) {
    entry(args);
    return;
  }
  (entry as dynamic Function())();
}

class _RaccoonBinding extends WidgetsFlutterBinding {
  @override
  Widget wrapWithDefaultView(Widget rootWidget) =>
${views ? '      _RaccoonViews(child: rootWidget);' : '      super.wrapWithDefaultView(_RaccoonDevice(child: rootWidget));'}
}
${views ? _views : ''}
/// The device [child]'s view is shown as, from the client: its safe area,
/// as MediaQuery.padding, and its platform.
class _RaccoonDevice extends StatefulWidget {
  const _RaccoonDevice({required this.child});

  final Widget child;

  @override
  State<_RaccoonDevice> createState() => _RaccoonDeviceState();
}

class _RaccoonDeviceState extends State<_RaccoonDevice>
    with WidgetsBindingObserver {
  static const _channel = BasicMessageChannel<Object?>(
    '$channel',
    JSONMessageCodec(),
  );

  static bool _overriding = false;

  int? _viewId;
  EdgeInsets? _padding;

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addObserver(this);
  }

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    final id = View.of(context).viewId;
    if (id == _viewId) return;
    _viewId = id;
    _ask();
  }

  @override
  void didChangeMetrics() => _ask();

  @override
  void dispose() {
    WidgetsBinding.instance.removeObserver(this);
    super.dispose();
  }

  Future<void> _ask() async {
    final Object? reply;
    try {
      reply = await _channel.send({'view': _viewId});
    } catch (_) {
      return;
    }
    if (!mounted || reply is! Map) return;
    final platform = reply['platform'];
    final wanted = TargetPlatform.values
        .where((value) => value.name == platform)
        .firstOrNull;
    // An override the app set itself stays, unless the client names one.
    if ((wanted != null || _overriding) &&
        wanted != debugDefaultTargetPlatformOverride) {
      debugDefaultTargetPlatformOverride = wanted;
      _overriding = wanted != null;
      WidgetsBinding.instance.reassembleApplication();
    }
    final padding = switch (reply['padding']) {
      [final num top, final num right, final num bottom, final num left] =>
        EdgeInsets.fromLTRB(
          left.toDouble(),
          top.toDouble(),
          right.toDouble(),
          bottom.toDouble(),
        ),
      _ => null,
    };
    if (padding != _padding) setState(() => _padding = padding);
  }

  @override
  Widget build(BuildContext context) {
    final padding = _padding;
    if (padding == null) return widget.child;
    final data = MediaQuery.of(context);
    final insets = data.viewInsets;
    // As MediaQueryData.fromView has it: what the keyboard covers is no
    // longer padding.
    return MediaQuery(
      data: data.copyWith(
        viewPadding: padding,
        padding: EdgeInsets.fromLTRB(
          math.max(0, padding.left - insets.left),
          math.max(0, padding.top - insets.top),
          math.max(0, padding.right - insets.right),
          math.max(0, padding.bottom - insets.bottom),
        ),
      ),
      child: widget.child,
    );
  }
}
''';

  static const _views = r'''
class _RaccoonViews extends StatefulWidget {
  const _RaccoonViews({required this.child});

  final Widget child;

  @override
  State<_RaccoonViews> createState() => _RaccoonViewsState();
}

class _RaccoonViewsState extends State<_RaccoonViews>
    with WidgetsBindingObserver {
  late List<int> _ids = _viewIds();

  static List<int> _viewIds() => [
    for (final view in WidgetsBinding.instance.platformDispatcher.views)
      view.viewId,
  ]..sort();

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addObserver(this);
  }

  @override
  void dispose() {
    WidgetsBinding.instance.removeObserver(this);
    super.dispose();
  }

  @override
  void didChangeMetrics() {
    final ids = _viewIds();
    if (ids.length == _ids.length &&
        ids.indexed.every((entry) => entry.$2 == _ids[entry.$1])) {
      return;
    }
    setState(() => _ids = ids);
  }

  @override
  Widget build(BuildContext context) {
    final dispatcher = WidgetsBinding.instance.platformDispatcher;
    return ViewCollection(
      views: [
        for (final id in _ids)
          if (dispatcher.view(id: id) case final view?)
            View(
              key: ValueKey(id),
              view: view,
              child: _RaccoonDevice(child: widget.child),
            ),
      ],
    );
  }
}
''';
}
